#Requires -Version 5.1
<#
.SYNOPSIS
  Scaffold the update feature into a target directory.

.DESCRIPTION
  Copies the updater crate, the Win32 GUI client, the release workflow, the
  key/signing tools and the docs into -TargetDir, then rewrites updater.conf.
  After that the target only needs a CHANGELOG entry, a tag and a push.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts/scaffold-update.ps1 `
    -TargetDir D:\code\my-app -Repo "me/my-app" -ExeName "MyApp.exe" -Product "my-app"
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$TargetDir,
    [Parameter(Mandatory)][string]$Repo,
    [Parameter(Mandatory)][string]$ExeName,
    [string]$Product,
    [string]$Homepage,
    [string]$WindowTitle,
    [int]$IntervalHours = 24,
    [int]$StartupDelaySeconds = 30,
    [string]$Variant = 'portable',
    [string]$Platform = 'windows-x64',
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$source = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$target = [IO.Path]::GetFullPath($TargetDir)

if (-not $Product) {
    $Product = ($Repo -split '/')[-1]
    if (-not $Product) { $Product = 'my-app' }
}
if (-not $Homepage) { $Homepage = "https://github.com/$Repo" }
if (-not $WindowTitle) { $WindowTitle = "$Product - version update" }

if (-not (Test-Path -LiteralPath $target)) {
    $null = New-Item -ItemType Directory -Force -Path $target
} elseif (-not $Force -and @(Get-ChildItem -LiteralPath $target -Force).Count -gt 0) {
    throw "Target directory is not empty: $target (use -Force to overwrite)"
}

function Copy-Tree([string]$relative) {
    $from = Join-Path $source $relative
    if (-not (Test-Path -LiteralPath $from)) { return }
    $to = Join-Path $target $relative
    $parent = Split-Path -Parent $to
    if ($parent -and -not (Test-Path -LiteralPath $parent)) {
        $null = New-Item -ItemType Directory -Force -Path $parent
    }
    Copy-Item -LiteralPath $from -Destination $to -Recurse -Force
}

Write-Output "source: $source"
Write-Output "target: $target"

foreach ($relative in @('Cargo.toml', 'Cargo.lock', 'build.rs', 'build-common', 'demo-app', 'src', 'resources', 'scripts', 'docs')) {
    Copy-Tree $relative
}

# Generated build artifacts and review archives must not be shipped.
foreach ($junk in @('dist', 'build', 'docs\reviews')) {
    $path = Join-Path $target $junk
    if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Recurse -Force }
}

$workflowDir = Join-Path $target '.github\workflows'
$null = New-Item -ItemType Directory -Force -Path $workflowDir
Copy-Item -LiteralPath (Join-Path $source '.github\workflows\build.yml') -Destination (Join-Path $workflowDir 'update-release.yml') -Force

$configLines = @(
    "repo=$Repo",
    "feed_name=latest-version-$Platform.json",
    "exe_name=$ExeName",
    "homepage=$Homepage",
    "variant=$Variant",
    "platform=$Platform",
    "interval_hours=$IntervalHours",
    "startup_check_delay_seconds=$StartupDelaySeconds",
    "product=$Product",
    "window_title=$WindowTitle",
    "require_signature=false"
)
[IO.File]::WriteAllText((Join-Path $target 'updater.conf'), ($configLines -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))

$changelog = @(
    '# Update log',
    '',
    '每个版本一节，顺序固定：新增 → 修改 → 删除。',
    '',
    '## 0.1.0',
    '',
    '### 新增',
    '- 接入自动更新：24 小时检查、手动刷新、下载校验、重启完成',
    '',
    '### 修改',
    '- 无',
    '',
    '### 删除',
    '- 无'
)
[IO.File]::WriteAllText((Join-Path $target 'CHANGELOG.md'), ($changelog -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))

$readme = @(
    "# $Product update module",
    '',
    'Generated by scripts/scaffold-update.ps1.',
    'Docs: docs/01 feature, docs/02 integration, docs/03 decisions.',
    '',
    '## Build',
    '',
    '    cargo build --release --workspace',
    '',
    '## Release',
    '',
    '1. 在 CHANGELOG.md 写当前版本小节（新增/修改/删除）',
    '2. git tag v0.1.0 && git push origin v0.1.0',
    "3. CI publishes zip + sha256 + latest-version-$Platform.json",
    '',
    '## Signing',
    '',
    '    powershell -File scripts/new-release-key.ps1 -PrivateKeyPath D:\keys\update-signing.pem -PublicKeysPath resources/update-trusted-keys.json',
    '私钥整段放进 GitHub Secret UPDATE_SIGNING_KEY，updater.conf 改 require_signature=true，再打 tag。',
    '',
    '## Config',
    '',
    '所有配置都在 updater.conf，构建时编译进 exe，发布包不需要 ini。'
)
[IO.File]::WriteAllText((Join-Path $target 'README-UPDATE.md'), ($readme -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))

Write-Output ''
Write-Output 'Created:'
Get-ChildItem -LiteralPath $target -Force | Select-Object -ExpandProperty Name | ForEach-Object { Write-Output "  $_" }
Write-Output ''
Write-Output 'Next:'
Write-Output '  1) cargo build --release --workspace'
Write-Output '  2) edit CHANGELOG.md, tag, push, wait for CI'
Write-Output '  3) optional: scripts/new-release-key.ps1 + UPDATE_SIGNING_KEY + require_signature=true'
